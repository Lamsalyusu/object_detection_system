from __future__ import annotations

import io
from typing import Any

from .marching_cubes import TriangleMesh
from .mesh_processing import MeshPostProcessor


class MeshExporter:
    """Serializes 3D TriangleMesh models to standard 3D file formats and client-side web representations."""

    @staticmethod
    def to_obj(mesh: TriangleMesh, object_name: str = "ReconstructedSurface") -> str:
        """Serializes mesh into standard Wavefront .OBJ format string.

        Outputs geometric vertices (v), vertex normals (vn), and face elements (f v//vn).
        """
        out = io.StringIO()
        out.write("# Wavefront OBJ generated by Smart Vision AI 3D Reconstruction\n")
        out.write(f"o {object_name}\n\n")

        # Vertices
        for v in mesh.vertices:
            out.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")

        # Normals
        has_normals = len(mesh.normals) == len(mesh.vertices)
        if has_normals:
            for n in mesh.normals:
                out.write(f"vn {n[0]:.6f} {n[1]:.6f} {n[2]:.6f}\n")

        # Faces (OBJ is 1-indexed)
        out.write("\n")
        for f in mesh.faces:
            idx0 = f[0] + 1
            idx1 = f[1] + 1
            idx2 = f[2] + 1
            if has_normals:
                out.write(f"f {idx0}//{idx0} {idx1}//{idx1} {idx2}//{idx2}\n")
            else:
                out.write(f"f {idx0} {idx1} {idx2}\n")

        return out.getvalue()

    @staticmethod
    def to_ply(mesh: TriangleMesh) -> str:
        """Serializes mesh into ASCII Stanford PLY format."""
        out = io.StringIO()
        n_verts = len(mesh.vertices)
        n_faces = len(mesh.faces)
        has_normals = len(mesh.normals) == n_verts

        out.write("ply\n")
        out.write("format ascii 1.0\n")
        out.write("comment SmartVisionAI Generated Mesh\n")
        out.write(f"element vertex {n_verts}\n")
        out.write("property float x\n")
        out.write("property float y\n")
        out.write("property float z\n")
        if has_normals:
            out.write("property float nx\n")
            out.write("property float ny\n")
            out.write("property float nz\n")
        out.write(f"element face {n_faces}\n")
        out.write("property list uchar int vertex_indices\n")
        out.write("end_header\n")

        for i in range(n_verts):
            v = mesh.vertices[i]
            if has_normals:
                n = mesh.normals[i]
                out.write(f"{v[0]:.6f} {v[1]:.6f} {v[2]:.6f} {n[0]:.6f} {n[1]:.6f} {n[2]:.6f}\n")
            else:
                out.write(f"{v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")

        for f in mesh.faces:
            out.write(f"3 {f[0]} {f[1]} {f[2]}\n")

        return out.getvalue()

    @staticmethod
    def to_threejs_json(mesh: TriangleMesh) -> dict[str, Any]:
        """Serializes mesh into Three.js BufferGeometry JSON format for immediate web rendering."""
        flat_vertices = mesh.vertices.flatten().round(6).tolist() if len(mesh.vertices) > 0 else []
        flat_normals = mesh.normals.flatten().round(6).tolist() if len(mesh.normals) > 0 else []
        flat_indices = mesh.faces.flatten().astype(int).tolist() if len(mesh.faces) > 0 else []

        bbox_min = mesh.vertices.min(axis=0).tolist() if len(mesh.vertices) > 0 else [0.0, 0.0, 0.0]
        bbox_max = mesh.vertices.max(axis=0).tolist() if len(mesh.vertices) > 0 else [0.0, 0.0, 0.0]
        area = MeshPostProcessor.compute_surface_area(mesh)

        return {
            "metadata": {
                "version": 4.5,
                "type": "BufferGeometry",
                "generator": "SmartVisionAI-MeshReconstructor",
            },
            "data": {
                "attributes": {
                    "position": {
                        "itemSize": 3,
                        "type": "Float32Array",
                        "array": flat_vertices,
                    },
                    "normal": {
                        "itemSize": 3,
                        "type": "Float32Array",
                        "array": flat_normals,
                    },
                },
                "index": {
                    "type": "Uint32Array",
                    "array": flat_indices,
                },
            },
            "statistics": {
                "vertex_count": len(mesh.vertices),
                "face_count": len(mesh.faces),
                "bounding_box": {
                    "min": bbox_min,
                    "max": bbox_max,
                },
                "surface_area_sq_m": round(area, 4),
            },
        }
